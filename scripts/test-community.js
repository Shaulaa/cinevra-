const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ctx = vm.createContext({});
vm.runInContext(fs.readFileSync('js/community-store.js', 'utf8'), ctx);
const { publication, item, create } = ctx.CinevraCommunity;
const draft = { kind: 'review', sourceKey: 'movie:1', displayName: ' Viewer ', body: '<img src=x onerror=alert(1)>', title: 'A film', rating: 8, spoilers: true, items: [{ id: 1, type: 'movie', title: 'A film', note: 'PRIVATE', episodes: ['1:1'], posterPath: 'https://evil.test/image.jpg' }] };
const result = publication(draft);
assert.equal(result.p_display_name, 'Viewer');
assert.equal(result.p_body, draft.body, 'Text stays text, rendering must use DOM text APIs');
assert.equal(result.p_items[0].posterPath, null);
assert.equal('note' in result.p_items[0], false);
assert.equal('episodes' in result.p_items[0], false);
for (const patch of [{ displayName: 'email@example.test' }, { body: '' }, { body: 'a'.repeat(601) }, { rating: 11 }, { items: [] }, { kind: 'bad' }]) assert.throws(() => publication({ ...draft, ...patch }));
assert.throws(() => item({ ...draft.items[0], id: 0 }));
(async () => {
  let actor = { id: 'one' }, resolve;
  const calls = [];
  const store = create({ user: () => actor, client: { rpc: async (name, args) => { calls.push({ name, args }); return { data: [], error: null }; } } });
  await store.feed({ cursor: { id: 'post', created_at: '2026-10-20T00:00:00Z' } });
  assert.equal(calls[0].args.p_before_id, 'post');
  await store.publish(draft);
  assert.equal(calls[1].name, 'community_publish');
  actor = null;
  await assert.rejects(store.like('post', true), /Sign in/);
  await store.feed();
  const missing = create({ user: () => null, client: { rpc: async () => ({ error: { code: 'PGRST202' } }) } });
  await assert.rejects(missing.feed(), /being prepared/);
  actor = { id: 'one' };
  const racing = create({ user: () => actor, client: { rpc: () => new Promise(done => { resolve = done; }) } });
  const request = racing.like('post', true); actor = { id: 'two' }; resolve({ data: true });
  await assert.rejects(request, /account changed/);
  console.log('Community public projection, draft validation, guest access, error handling and account-race tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });

const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const context = vm.createContext({ console, URL });
vm.runInContext(fs.readFileSync('js/cloud-store.js', 'utf8'), context);
const { createStore, changes, validateGuest } = context.CinevraStoreFactory;
const empty = () => ({ cinevra_watchlist: [], cinevra_lists: [], cinevra_personal: {} });
const data = new Map();
const storage = { getItem: key => data.get(key) || null, setItem: (key, value) => data.set(key, value) };
const guest = createStore({ storage });
guest.write('cinevra_watchlist', '[{"id":10,"type":"movie","title":"Guest"}]');
assert.equal(JSON.parse(guest.read('cinevra_watchlist'))[0].title, 'Guest');
assert.equal(guest.state().user, null);
const beforeGuest = new Map(data);
let failed = false;
let owner = '';
let resolveWrite;
let pauseWrite = false;
let pauseRead = false;
const readResolvers = [];
const calls = [];
const rows = { watchlist_items: [], custom_lists: [], custom_list_items: [], personal_reviews: [], watched_episodes: [] };
const client = {
  from(table) { return { select() { return this; }, eq(field, value) { owner = value; return this; }, order() { return this; }, async range(start, end) { if (pauseRead) await new Promise(resolve => readResolvers.push(resolve)); return { data: rows[table].slice(start, end + 1), error: failed ? Error('offline') : null }; } }; },
  async rpc(name, args) { calls.push({ name, args }); if (pauseWrite) await new Promise(resolve => { resolveWrite = resolve; }); return { error: failed ? Error('failed') : null }; },
};
const store = createStore({ storage, client });
(async () => {
  assert.throws(() => store.read('cinevra_watchlist'));
  await store.setUser({ id: 'account-a' });
  assert.equal(owner, 'account-a');
  assert.equal(store.read('cinevra_watchlist'), '[]', 'Guest data must not become cloud data automatically');
  await store.write('cinevra_watchlist', '[{"id":20,"type":"tv","title":"Cloud"}]');
  assert.equal(calls[0].name, 'library_apply');
  assert.equal(calls[0].args.p_changes.length, 1);
  assert.equal(calls[0].args.p_changes[0].row.tmdb_id, 20);
  assert.deepEqual(data, beforeGuest);
  failed = true;
  await assert.rejects(store.write('cinevra_watchlist', '[]'));
  assert.equal(JSON.parse(store.read('cinevra_watchlist')).length, 1, 'A failed save must not erase the acknowledged snapshot');
  failed = false;
  pauseWrite = true;
  const pending = store.write('cinevra_watchlist', '[]');
  await assert.rejects(store.write('cinevra_lists', '[]'), /Another change/);
  await store.setUser({ id: 'account-b' });
  resolveWrite();
  await assert.rejects(pending, /account changed/);
  assert.equal(store.read('cinevra_watchlist'), '[]');
  pauseWrite = false;
  await store.importGuest();
  assert.equal(calls.at(-1).name, 'library_import');
  assert.deepEqual(data, beforeGuest, 'Import must preserve guest storage');
  failed = true;
  await assert.rejects(store.refresh());
  assert.throws(() => store.read('cinevra_watchlist'), /unavailable/);
  assert.throws(() => store.write('cinevra_watchlist', '[]'));
  assert.deepEqual(data, beforeGuest);
  failed = false;
  await store.setUser(null);
  assert.equal(JSON.parse(store.read('cinevra_watchlist'))[0].title, 'Guest');
  const before = empty(), after = empty();
  before.cinevra_personal['tv:10'] = { rating: 8, note: 'Keep this', episodes: ['1:1'] };
  after.cinevra_personal['tv:10'] = { rating: 8, note: 'Keep this', episodes: ['1:1', '1:2'] };
  const delta = changes(before, after);
  assert.equal(delta.length, 1);
  assert.equal(delta[0].table, 'watched_episodes', 'Episode changes must not overwrite a review');
  assert.throws(() => validateGuest({ ...empty(), cinevra_watchlist: [{}] }));
  assert.throws(() => validateGuest({ ...empty(), cinevra_personal: { '__proto__:10': { note: 'x' } } }));
  assert.throws(() => validateGuest({ ...empty(), cinevra_personal: { 'movie:1': { watchedOn: '2025-02-29' } } }));
  rows.watchlist_items = Array.from({ length: 1101 }, (_, index) => ({ payload: { id: index + 1, type: 'movie', title: 'Saved title' } }));
  await store.setUser({ id: 'account-a' });
  assert.equal(JSON.parse(store.read('cinevra_watchlist')).length, 1101, 'Paginate beyond the default API row limit');
  rows.watchlist_items = [];
  pauseRead = true;
  const pendingRefresh = store.refresh();
  await assert.rejects(store.write('cinevra_watchlist', '[]'), /Another change/);
  pauseRead = false;
  await store.setUser({ id: 'account-b' });
  readResolvers.forEach(resolve => resolve());
  await assert.rejects(pendingRefresh, /account changed/);
  assert.equal(store.state().phase, 'ready', 'An old refresh must not put the new account into an error state');
  console.log('Cloud storage isolation, failure, account-race, import and entry-level change tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
